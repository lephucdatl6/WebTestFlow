import { RecordedAction } from '../../shared/types/recording';
import { locatorDescriptionFor, locatorExpressionFor, narrowLocatorExpressionByValue } from '../browser/locator-resolution';

const temporaryParameterNames = new Set(['solution', 'js_challenge', 'jsc_token', 'jsc_orig_r', 'cid', 'iid', 'fbclid', 'gclid']);

function stableSelector(selector: string): string {
	const match = /^a\[href="([\s\S]*)"\]$/.exec(selector);
	if (!match) {
		return selector;
	}

	const href = match[1];
	const queryStart = href.indexOf('?');
	if (queryStart < 0) {
		return selector;
	}

	const path = href.slice(0, queryStart);
	const queryParts = href.slice(queryStart + 1).split('&');
	const firstTemporaryIndex = queryParts.findIndex((part) => {
		const parameterName = decodeURIComponent(part.split('=')[0]).toLowerCase();
		return temporaryParameterNames.has(parameterName) || parameterName.startsWith('utm_');
	});
	if (firstTemporaryIndex < 0) {
		return selector;
	}

	const stablePrefix = queryParts.slice(0, firstTemporaryIndex).join('&');
	const prefix = `${path}${stablePrefix ? `?${stablePrefix}` : ''}`;
	return `a[href^=${JSON.stringify(prefix)}]`;
}

function locatorFor(action: Extract<RecordedAction, { selector: string }>): string {
	return locatorExpressionFor(action, stableSelector);
}

function narrowLocatorFor(action: Extract<RecordedAction, { selector: string }>): string {
	const value = 'value' in action && typeof action.value === 'string' ? action.value : undefined;
	const expression = locatorFor(action);
	if (value) {
		return narrowLocatorExpressionByValue(expression, value);
	}
	// A value-less radio check narrows to the radio the user selected (the checked one).
	if (action.type === 'check' && action.selector.toLowerCase().includes('type="radio"')) {
		return `${expression}.and(locator('input[type="radio"]:checked'))`;
	}
	return expression;
}

function locatorDescription(action: Extract<RecordedAction, { selector: string }>): string {
	return action.description ?? locatorDescriptionFor(action);
}

function step(name: string, statement: string): string[] {
	return [
		`  await test.step(${JSON.stringify(name)}, async () => {`,
		`    ${statement}`,
		'  });'
	];
}

// Wrap a locator-based step so that on failure the target element is scrolled into
// view and outlined before Playwright's only-on-failure screenshot is captured.
function stepWithLocator(name: string, locatorCode: string, statement: string): string[] {
	return [
		`  await test.step(${JSON.stringify(name)}, async () => {`,
		`    const target = page.${locatorCode};`,
		'    try {',
		`      ${statement}`,
		'    } catch (error) {',
		'      await outlineFailure(target);',
		'      throw error;',
		'    }',
		'  });'
	];
}

export function generatePlaywrightTest(name: string, startUrl: string | undefined, actions: RecordedAction[]): string {
	const hasFillActions = actions.some((action) => action.type === 'fill');
	const lines = [
		'// Generated by WebTestFlow',
		"import { test, expect, type Locator } from '@playwright/test';",
		''
	];

	lines.push(
		'async function outlineFailure(locator: Locator): Promise<void> {',
		'  try {',
		'    const target = locator.first();',
		'    await target.scrollIntoViewIfNeeded();',
		'    await target.evaluate((element) => {',
		'      const html = element as HTMLElement;',
		'      html.style.outline = "3px solid #ff5722";',
		'      html.style.outlineOffset = "2px";',
		'    });',
		'  } catch {',
		'    // Element could not be outlined; screenshot the page as-is.',
		'  }',
		'}',
		''
	);

	if (hasFillActions) {
		lines.push(
			'async function fillControl(locator: Locator, value: string): Promise<void> {',
			'  const controlKind = await locator.evaluate((element) =>',
			'    element instanceof HTMLSelectElement',
			'      ? "select"',
			'      : element instanceof HTMLInputElement && element.type === "radio"',
			'        ? "radio"',
			'        : "text");',
			'  if (controlKind === "select") {',
			'    await locator.selectOption(value);',
			'  } else if (controlKind === "radio") {',
			'    await locator.check();',
			'  } else {',
			'    await locator.fill(value);',
			'  }',
			'}',
			''
		);
	}

	lines.push(`test(${JSON.stringify(name)}, async ({ page }) => {`);

	if (startUrl) {
		lines.push(...step(`Navigate to ${startUrl}`, `await page.goto(${JSON.stringify(startUrl)});`));
	}

	for (let index = 0; index < actions.length; index += 1) {
		const action = actions[index];
		const nextAction = actions[index + 1];
		if (
			action.type === 'click' &&
			nextAction?.type === 'fill' &&
			(action.selector === nextAction.selector || action.playwright === nextAction.playwright)
		) {
			continue;
		}

		switch (action.type) {
			case 'navigate':
				lines.push(...step(`Navigate to ${action.url}`, `await page.goto(${JSON.stringify(action.url)});`));
				break;
			case 'click':
				lines.push(...stepWithLocator(`Click ${locatorDescription(action)}`, locatorFor(action), `await target.click();`));
				break;
			case 'fill':
				if (action.selector.toLowerCase().includes('type="radio"')) {
					lines.push(...stepWithLocator(`Check ${locatorDescription(action)}`, narrowLocatorFor(action), `await target.check();`));
				} else {
					lines.push(...stepWithLocator(`Fill ${locatorDescription(action)}`, locatorFor(action), `await fillControl(target, ${JSON.stringify(action.value)});`));
				}
				break;
			case 'check':
				lines.push(...stepWithLocator(`Check ${locatorDescription(action)}`, narrowLocatorFor(action), `await target.check();`));
				break;
			case 'uncheck':
				lines.push(...stepWithLocator(`Uncheck ${locatorDescription(action)}`, narrowLocatorFor(action), `await target.uncheck();`));
				break;
			case 'submit': {
				const previousAction = actions[index - 1];
				const inputAction = previousAction?.type === 'fill' ? previousAction : action;
				lines.push(...stepWithLocator(`Press Enter on ${locatorDescription(inputAction)}`, locatorFor(inputAction), `await target.press("Enter");`));
				break;
			}
			case 'assert-url':
				lines.push(...step(`Assert URL contains ${JSON.stringify(action.value)}`, `await expect(page).toHaveURL(url => url.toString().includes(${JSON.stringify(action.value)}));`));
				break;
			case 'assert-text':
				lines.push(...step(`Assert ${JSON.stringify(action.text)} is visible`, `await expect(page.getByText(${JSON.stringify(action.text)})).toBeVisible();`));
				break;
			case 'assert-element':
				lines.push(...stepWithLocator(`Assert ${locatorDescription(action)} exists`, locatorFor(action), `await expect(target.first()).toBeAttached();`));
				break;
			case 'assert-title':
				lines.push(...step(`Assert page title ${JSON.stringify(action.title)}`, `await expect(page).toHaveTitle(${JSON.stringify(action.title)});`));
				break;
			case 'assert-state': {
				const matcher = action.state === 'visible' ? 'toBeVisible' : action.state === 'enabled' ? 'toBeEnabled' : action.state === 'disabled' ? 'toBeDisabled' : 'toBeChecked';
				lines.push(...stepWithLocator(`Assert ${locatorDescription(action)} is ${action.state}`, locatorFor(action), `await expect(target).${matcher}();`));
				break;
			}
		}
	}

	lines.push('});', '');
	return lines.join('\n');
}